// The elevated helper for the Windows OpenVPN tunnel.
//
// ## What this is
//
// `openvpn.exe` needs Administrator: it creates the TUN adapter through wintun
// and installs routes. The Flutter application itself must not run elevated — an
// app that asks for Administrator is an app whose every bug lands with the
// user's full rights attached. So the privileged work happens in this small
// separate program, built with a `requireAdministrator` manifest, which the app
// starts *only* when a tunnel is actually requested.
//
// ## What it does not do
//
// It has no user interface, no network access of its own and no persistence. It:
//
//   1. connects to a named pipe the app created for it;
//   2. proves it is the process the app launched, by echoing a token the app
//      chose and passed on the command line;
//   3. runs `openvpn.exe` from the bundled community binaries as its own child;
//   4. reports what the engine says, and stops when told to;
//   5. exits when the app that launched it goes away.
//
// It never parses the profile beyond one defensive check. The application writes
// it, restricts its ACL, and hands this program three paths; the elevated engine
// then reads it. The check exists because the engine reads the file as
// Administrator, and "the sender already checked" is not a property of the
// receiver.
//
// ## Why there is no service
//
// A service would survive the application closing, which is exactly what a VPN
// client must not do silently: a tunnel that stays up after the user closed the
// app is a leak, not a convenience. This helper waits on the application's
// process handle for its entire life and exits with it, stopping the engine on
// the way out.

